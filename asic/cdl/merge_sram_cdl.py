"""Merges the SRAM macro CDLs used on the chip into sram.cdl for KLayout LVS.

Every PDK SRAM CDL carries its own copy of the shared RSC_IHPSG13_* helper
cells; concatenated, KLayout LVS stops with "Redefinition of circuit". Each
subcircuit is kept once (duplicates must be identical, else this fails).

Usage: python3 merge_sram_cdl.py   (re-run when the macro list changes)
"""
import re

PDK = '/opt/IHP-Open-PDK/ihp-sg13cmos5l/libs.ref/sg13cmos5l_sram/cdl/'
MACROS = ['1024x32_c2', '1024x8_c2', '1024x16_c2', '256x48_c2',     # config.yaml
          '2048x32_c2', '4096x8_c3', '4096x16_c3']                 # config_d10000.yaml

subckts = {}
for m in MACROS:
    text = open(f'{PDK}RM_IHPSG13_1P_{m}_bm_bist.cdl').read()
    for block in re.findall(r'^\.SUBCKT .*?^\.ENDS\b.*?$', text, re.M | re.S | re.I):
        name = block.split()[1]
        norm = '\n'.join(l.rstrip() for l in block.splitlines())
        if name in subckts:
            assert subckts[name] == norm, f'{name} differs between SRAM CDLs'
        else:
            subckts[name] = norm

with open('sram.cdl', 'w') as f:
    f.write('* Generated by merge_sram_cdl.py from the PDK SRAM CDLs: '
            + ', '.join(MACROS) + '\n\n')
    f.write('\n\n'.join(subckts.values()) + '\n')
print(len(subckts), 'subcircuits')
